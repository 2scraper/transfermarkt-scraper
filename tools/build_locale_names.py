#!/usr/bin/env python3
"""Build locale_names.py — every country and position name the site prints,
per locale, from the site's OWN filter lists.

Why: product_parser's tables were built from players seen on a few pages,
and every new squad brought names they lacked (2026-10-21: three club squads
on .de/.world/.co.kr logged Österreich, Japan, Ukraine, Polen,
"Hängende Spitze", ...). The market-value ranking page carries the full
lists as filter <select>s — `land_id` (254 countries) and
`spielerposition_id` (16 positions) — with the SAME option values on every
host and the text in that host's language. Pairing by value gives complete
tables, and the text is what the site prints on a player's flag: checked
against every pair measured from players (63 de, 61 ru, 61 ko country
pairs, 11 position pairs per locale), 0 disagreements, the site's odd
Korean "이동" (Togo) included.

Usage — one ranking page per host, saved by the scraper itself:

    python3 playwright_scraper.py --mode market-values --dump-html en.html \\
        --out /tmp/x
    python3 playwright_scraper.py --mode market-values --dump-html de.html \\
        --out /tmp/x --url https://www.transfermarkt.de/spieler-statistik/wertvollstespieler/marktwertetop
    ... (.world, .co.kr, .jp likewise)
    python3 tools/build_locale_names.py --en en.html --de de.html \\
        --ru ru.html --ko ko.html --ja ja.html

It refuses to write if any list disagrees with a pair product_parser
already holds, or if a list is missing or carries a duplicate name.
"""
import argparse
import os
import sys

from bs4 import BeautifulSoup

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

LISTS = {"nationality": "land_id", "position": "spielerposition_id"}
LOCALES = ("de", "ru", "ko", "ja")
SKIP_VALUES = {"0", "alle"}  # the "All" / "Worldwide" option


def options(html: str, name: str) -> dict:
    sel = BeautifulSoup(html, "html.parser").find("select", attrs={"name": name})
    if sel is None:
        raise SystemExit(f"no <select name={name!r}> in the page — not a ranking page?")
    out = {}
    for o in sel.find_all("option"):
        value, text = o.get("value"), o.get_text(strip=True)
        if value in SKIP_VALUES or not text:
            continue
        out[value] = text
    if len(set(out.values())) != len(out):
        raise SystemExit(f"duplicate names in {name!r}: cannot map by text")
    return out


def build(pages: dict) -> dict:
    tables = {kind: {} for kind in LISTS}
    for kind, name in LISTS.items():
        en = options(pages["en"], name)
        for loc in LOCALES:
            local = options(pages[loc], name)
            pairs = {local[v]: en[v] for v in local if v in en}
            if loc == "ja" and kind == "nationality":
                # Japanese flags are English already; keep only the names
                # the Japanese site prints differently (e.g. "Turkey").
                pairs = {k: v for k, v in pairs.items() if k != v}
            tables[kind][loc] = dict(sorted(pairs.items()))
    return tables


def check_against_measured(tables: dict) -> list:
    import product_parser as pp
    problems = []
    for kind, measured in (("nationality", pp._NATIONALITY_EN_MEASURED),
                           ("position", pp._POSITION_EN_MEASURED)):
        for loc, pairs in measured.items():
            for k, v in pairs.items():
                got = tables[kind].get(loc, {}).get(k, k if loc == "ja" else None)
                if got != v:
                    problems.append(f"{kind} {loc}: {k!r} measured {v!r}, list says {got!r}")
    return problems


def render(tables: dict) -> str:
    import pprint
    lines = ['"""GENERATED by tools/build_locale_names.py — do not edit by hand.',
             "",
             "Country and position names per locale, paired by the site's own",
             "filter-list values (land_id, spielerposition_id) on the market-value",
             "ranking page of each host. Some names are the site's own odd",
             "translations (Korean \"이동\" for Togo, Japanese \"Grenadaj\") and are",
             "kept as printed: they are what a player's flag says.",
             '"""', ""]
    for kind, const in (("nationality", "NATIONALITY_EN"), ("position", "POSITION_EN")):
        lines.append(f"{const} = {{")
        for loc in LOCALES:
            body = pprint.pformat(tables[kind][loc], width=72, sort_dicts=True)
            lines.append(f"    {loc!r}: {body.replace(chr(10), chr(10) + '        ')},")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    for loc in ("en",) + LOCALES:
        p.add_argument(f"--{loc}", required=True,
                       help=f"saved ranking page from the {loc} host")
    p.add_argument("--out", default=os.path.join(ROOT, "locale_names.py"))
    args = p.parse_args()
    pages = {loc: open(getattr(args, loc), encoding="utf-8").read()
             for loc in ("en",) + LOCALES}
    tables = build(pages)
    problems = check_against_measured(tables)
    if problems:
        print("Refusing to write — the lists disagree with measured pairs:")
        for line in problems:
            print("  " + line)
        return 1
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(render(tables))
    for kind in LISTS:
        print(f"{kind}: " + ", ".join(f"{loc} {len(tables[kind][loc])}" for loc in LOCALES))
    print(f"written: {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
